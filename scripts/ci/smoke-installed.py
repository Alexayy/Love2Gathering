#!/usr/bin/env python3
"""Start the compiled Linux services against isolated one-card metadata."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import sqlite3
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--payload', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args();payload = args.payload.resolve()
    precons = payload/'decks/preconstructed/catalog.jsonl.gz'
    if not precons.is_file():raise RuntimeError('Compiled payload is missing its bundled preconstructed catalog')
    products = json.loads((precons.parent/'manifest.json').read_text())
    with tempfile.TemporaryDirectory(prefix='l2g-ci-services-', dir=os.environ.get('RUNNER_TEMP')) as temporary:
        base = Path(temporary);source = base / 'cards.jsonl'
        source.write_text(json.dumps({'object':'card','id':'ci-printing','oracle_id':'ci-oracle','name':'CI Card','lang':'en','type_line':'Artifact','colors':[],'color_identity':[],'set':'tst','legalities':{'modern':'legal'}}) + '\n')
        env = os.environ.copy()
        for key in ('LOVE2GATHERING_STORAGE_RESOLVED','LOVE2GATHERING_DATA_DIR_EXPLICIT','LOVE2GATHERING_CACHE_DIR_EXPLICIT','LOVE2GATHERING_STARTUP_STATUS','LOVE2GATHERING_PRECON_SOURCE'):env.pop(key,None)
        env.update(LOVE2GATHERING_DATA_DIR=str(base/'saves'),LOVE2GATHERING_CACHE_DIR=str(base/'cache'),
                   LOVE2GATHERING_CONFIG_DIR=str(base/'config'),XDG_DATA_HOME=str(base/'xdg'),
                   LOVE2GATHERING_CATALOG_SOURCE=str(source))
        check = subprocess.run([str(payload/'love2gathering'),'--check'], env=env, capture_output=True, text=True, timeout=30)
        if check.returncode:raise RuntimeError(check.stderr or check.stdout)
        result = subprocess.run([str(payload/'love2gathering'),'--checkhealth'], env=env, capture_output=True, text=True, timeout=70)
        if result.returncode:raise RuntimeError(result.stderr or result.stdout)
        health = json.loads(result.stdout.strip().splitlines()[-1])
        if not health.get('passed') or health['catalog'].get('apiVersion',0)<14 or health['engine'].get('engine')!='XMage':
            raise RuntimeError('Compiled services did not acknowledge readiness')
        with sqlite3.connect((base/'saves/app.sqlite').as_uri()+'?mode=ro', uri=True) as connection:
            rows = dict(connection.execute('SELECT category,COUNT(*) FROM preconstructed WHERE active=1 GROUP BY category'))
        if rows != products['categories']:
            raise RuntimeError('Installed catalog did not load every bundled preconstructed product')
        manifest = json.loads((payload/'payload-manifest.json').read_text())['files']
        for relative, expected in manifest.items():
            with (payload/relative).open('rb') as stream:actual = hashlib.file_digest(stream,'sha256').hexdigest()
            if actual != expected:raise RuntimeError('Runtime changed an installed file: ' + relative)
        if list(payload.rglob('__pycache__')):raise RuntimeError('Runtime generated bytecode in the payload')
        report = {'passed':True,'scope':'Actual compiled Linux Python/Java/XMage/catalog/gateway against explicit temporary one-card metadata; no full index, GUI, Windows, WAN or match assertion.',
                  'versions':json.loads(check.stdout),'apiVersion':health['catalog']['apiVersion'],'payloadFilesVerified':len(manifest),
                  'bundledProducts':rows,'temporaryUserStorageOnly':True}
        args.report.parent.mkdir(parents=True,exist_ok=True)
        args.report.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report))


if __name__=='__main__':main()
